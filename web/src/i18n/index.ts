const dicts: Record<Locale, Dict> = {
  'zh-CN': zhCN,
  'en-US': enUS,
}

export function useI18n() {
  const locale = useUIStore((s) => s.locale)
  const setLocale = useUIStore((s) => s.setLocale)
  return { locale, setLocale, t: dicts[locale] }
}
